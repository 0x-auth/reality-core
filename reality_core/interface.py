"""The contract every law plugs into. Signatures only — implementations live
in mobius.py and linear.py."""

from __future__ import annotations

import random
from typing import Any, Protocol


class LawType(Protocol):
    name: str
    looks: int

    def step(self, state: Any) -> Any: ...
    def observe(self, state: Any) -> float: ...
    @property
    def delta(self) -> float: ...
    def sector(self) -> str: ...
    def to_dict(self) -> dict: ...


class Recognizer(Protocol):
    law_type: str
    looks: int

    def random_law(self, rng: random.Random, sector: str | None = None) -> LawType: ...
    def initial_state(self, rng: random.Random) -> Any: ...
    def fit(self, readings: list) -> LawType: ...
    def verify(self, claimed_law: LawType, readings: list) -> bool: ...
    def from_dict(self, d: dict) -> LawType: ...
